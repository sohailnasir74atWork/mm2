#!/usr/bin/env node
/**
 * Pack Code/Manor/game/manor.html into Code/Manor/manorGameHtml.js, the
 * string the app hands to react-native-webview (source={{ html }}). The game
 * ships inside the app bundle: no download, no remote code.
 *
 *   npm run manor:build        (after every edit to manor.html)
 *
 * __tests__/manorGame.test.js fails when the two drift apart.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const src = path.join(root, 'Code/Manor/game/manor.html');
const out = path.join(root, 'Code/Manor/manorGameHtml.js');
const html = fs.readFileSync(src, 'utf8');
fs.writeFileSync(out, `// GENERATED by scripts/manor/build-game.js from Code/Manor/game/manor.html. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`manorGameHtml.js written (${(html.length / 1024).toFixed(1)} KB)`);
